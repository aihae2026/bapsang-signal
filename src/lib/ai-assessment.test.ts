// AI 로 보내기 전 가리기(maskNames) — 회귀 테스트
//
// 이 테스트가 있는 이유는 양쪽으로 다 사고가 났기 때문입니다.
//
//   ① 못 가려서 샌 쪽 — "따님 성춘향 통화" 의 실명이 **그대로 Anthropic 으로 갔습니다.**
//      관계어 목록에 「따님·아드님」 같은 높임말이 빠져 있었습니다. 현장 기록은 거의 항상
//      높임말로 적습니다.
//
//   ② 과하게 가려서 근거가 지워진 쪽 — "이웃 전언으로 돌아가셨다고 함" 이
//      "이웃 ○○로 돌아가셨다고 함" 이 되었습니다. 사라진 「전언」은 「전해 들은 이야기면
//      명단에서 빼지 않는다」를 판정하는 **유일한 단서**입니다. 그게 지워지면 AI 가
//      확인불가 대신 사망·요양원입소를 골라, 살아 계신 분이 명단에서 영구히 빠집니다.
//
// 가리기를 손볼 때는 두 방향을 같이 봐야 합니다. 한쪽만 보면 반드시 다른 쪽이 깨집니다.
//
// 실행: bun test
//
// ※ 이 파일의 사람 이름(홍길동·성춘향 등)은 모두 지어낸 가상 이름입니다. 실제 어르신·가족과
//   관계없으며, 가리기 규칙이 어떤 모양에서 새는지를 보여주려고 같은 꼴로 지었습니다.

import { describe, expect, it } from "bun:test";
import { maskNames } from "./ai-assessment";

describe("실명은 가립니다", () => {
  it("높임말 관계어 뒤의 이름 — 현장 기록은 거의 이렇게 적습니다", () => {
    expect(maskNames("따님 성춘향 통화")).not.toContain("성춘향");
    expect(maskNames("아드님 이몽룡 연락처 확인")).not.toContain("이몽룡");
    expect(maskNames("자제분 전우치 만남")).not.toContain("전우치");
  });

  it("평어 관계어 뒤의 이름", () => {
    expect(maskNames("딸 홍길순이 받으심")).not.toContain("홍길순");
    expect(maskNames("보호자 심학규 통화")).not.toContain("심학규");
  });

  it("호칭이 뒤에 붙는 꼴", () => {
    expect(maskNames("홍길동 아드님께 연락")).not.toContain("홍길동");
    expect(maskNames("임꺽정 님 부재")).not.toContain("임꺽정");
  });

  it("사람에게만 붙는 조사 앞", () => {
    expect(maskNames("심청이께 전화 드림")).not.toContain("심청이");
    expect(maskNames("홍길숙한테 물어봄")).not.toContain("홍길숙");
  });

  it("번호·주소는 형태가 또렷하니 확실히 가립니다", () => {
    expect(maskNames("010-1234-5678 로 연락")).toContain("(전화번호)");
    expect(maskNames("주민번호 480101-2345678")).toContain("(주민번호)");
    expect(maskNames("방송길 86 거주")).toContain("(주소)");
  });
});

describe("판단 근거는 지우지 않습니다", () => {
  it("「전언」이 남아야 전해 들은 말인 줄 압니다 — 이게 지워지면 산 분이 명단에서 빠집니다", () => {
    expect(maskNames("이웃 전언으로 돌아가셨다고 함")).toContain("전언");
  });

  it("기관·장소 이름은 이름이 아닙니다", () => {
    expect(maskNames("이웃 요양원에 가셨다는 말")).toContain("요양원");
    expect(maskNames("가족 장례식장에 다녀오심")).toContain("장례식");
    expect(maskNames("딸 서울에 가 계심")).toContain("서울");
    expect(maskNames("아들 병원에 모시고 감")).toContain("병원");
    expect(maskNames("보호자 전화번호 없음")).toContain("전화번");
  });

  it("복귀 예정일은 판단에 필요하니 그냥 날짜는 가리지 않습니다", () => {
    expect(maskNames("10월 5일쯤 나오신다고 하심")).toContain("10월 5일");
  });

  it("주소처럼 보이는 말이 실은 상태 설명일 때", () => {
    expect(maskNames("거동 1개월째 어려우심")).toContain("거동 1개월째");
    expect(maskNames("산책로 3바퀴 도신다고 함")).toContain("산책로");
  });
});

