// 개인정보 점검에서 **실제로 새고 있던** 모양의 문장들(이름은 가상).
//
// 아래는 전부 그때 maskNames 를 그대로 통과해 미국(Anthropic)으로 나가던 것입니다.
// 어르신 실명 + 병명·사망(민감정보), 그리고 동의한 적 없는 가족 실명입니다.
//
// 세 가지가 겹쳐 있었습니다 —
//   ① 규칙 ①은 이름 **뒤**에 호칭이 와야 하는데, 현장 기록은 "변사또 며느리"처럼
//      관계어가 뒤에 옵니다
//   ② 규칙 ③은 조사가 께·에게·한테일 때만 봤습니다. 정작 흔한 이/가/은/는/을/를이
//      빠져 있었습니다
//   ③ 전화번호 규칙이 0으로 시작하는 국번을 요구해, 지역번호를 생략한 시내번호
//      (241-5600 — 홀몸 어르신 댁에서 가장 흔한 꼴)가 전부 통과했습니다
// ─────────────────────────────────────────────────────────────────────
describe("개인정보 점검에서 새던 문장들", () => {
  const 새면안됨: [string, string][] = [
    ["홍길자 본인 통화. 무릎 수술 후 거동 불편", "홍길자"],
    ["변사또 며느리 통화함. 요양원 상담 중", "변사또"],
    ["홍길남 사망하셨다고 주민센터에서 알려옴", "홍길남"],
    ["홍길녀 폐암 3기 진단받으셨다고 하심", "홍길녀"],
    ["홍길녀가 전화 받으심", "홍길녀"],
    ["홍길숙을 만나뵙지 못함", "홍길숙"],
    ["홍길옥 입원 중이심", "홍길옥"],
    ["홍말순 낙상으로 골절", "홍말순"],
    ["자택 241-5600", "241-5600"],
  ];
  for (const [문장, 새면안되는것] of 새면안됨) {
    it(`"${문장}" 에서 「${새면안되는것}」이 나가지 않습니다`, () => {
      expect(maskNames(문장)).not.toContain(새면안되는것);
    });
  }
});

describe("가려도 판단 근거는 그대로 남습니다", () => {
  // 과하게 가리면 AI 가 갈래를 잘못 고릅니다. 살아 계신 분이 명단에서 빠지는
  // 쪽이 이름 한 글자보다 훨씬 위험합니다.
  const 그대로 = [
    "이웃 전언으로 돌아가셨다고 함",
    "이웃 요양원에 가셨다는 말",
    "가족 장례식장에 다녀오심",
    "보호자 전화번호 없음",
    "10월 5일쯤 나오신다고 하심",
    "거동 1개월째 어려우심",
    "몸이 좋지 않아서 못 나왔었음. 다음주부터 다시 나올 예정",
    "지난주 뇌경색으로 대학병원 입원 중",
    "노년사회화교육 참여중",
    "주민센터에서 확인함",
    "경로당에 다니심",
    "일자리 나가심",
    "무릎 수술하셨다고 본인이 말씀하심",
    "특이사항 없음",
    "전화 안 받으심. 이웃 말로는 돌아가셨다고 함",
  ];
  for (const 문장 of 그대로) {
    it(`"${문장}" 는 손대지 않습니다`, () => {
      expect(maskNames(문장)).toBe(문장);
    });
  }

  // ── 제출 전 감사에서 실제로 새던 것들 ────────────────────────────
  //
  // 아래는 전부 **실명이 그대로 AI 로 나가던** 문장입니다. 규칙이 없어서가 아니라
  // 성씨 목록에 그 성이 없거나, 이름 끝 글자를 동사 어미로 오인해서였습니다.
  // 새는 모양을 볼 때마다 여기에 한 줄씩 굳힙니다.
  const 성씨목록에_없어_새던_것 = [
    "엄길순이 통화함",
    "채길자가 사망",
    "천길숙은 입원",
    "함길자가 별세",
    "보호자 엄길숙 통화, 어머니 낙상으로 입원",
    "딸 채길선이 받으심",
  ];
  const 이름_끝글자를_어미로_오인해_새던_것 = [
    "홍순이가 통화",
    "홍옥이가 사망",
    "홍영지가 수술",
    "딸 홍순이가 받으심",
  ];
  for (const 문장 of [...성씨목록에_없어_새던_것, ...이름_끝글자를_어미로_오인해_새던_것]) {
    it(`"${문장}" 에서 이름이 남지 않습니다`, () => {
      expect(maskNames(문장)).not.toBe(문장);
      expect(maskNames(문장)).toContain("○");
    });
  }

  // ── 반대쪽: 호칭 앞이라고 무조건 가리다 뜻을 지우던 것 ───────────
  //
  // 「알아보는 중」이 지워지면 AI 는 **위기** 대신 **요양원입소**를 고르고,
  // 아직 댁에 계신 어르신이 명단에서 영구히 빠집니다. 이름 한 글자보다
  // 훨씬 위험한 실패라 따로 묶어 둡니다.
  const 호칭_앞이라고_지우면_안_되는_것 = [
    "요양원 알아보신다고 따님이 말씀",
    "무릎 아프다고 어르신 말씀",
    "다음주 나오신다고 아드님 전함",
    "퇴원하셨다고 따님 통화",
    "입원하셨다는 할머니 이웃 전언",
    "1948년생 어르신",
  ];
  for (const 문장 of 호칭_앞이라고_지우면_안_되는_것) {
    it(`"${문장}" 의 판단 근거를 지우지 않습니다`, () => {
      expect(maskNames(문장)).toBe(문장);
    });
  }

  // 이름은 여전히 가려야 합니다 — 위 완화가 이름까지 풀어주면 안 됩니다.
  it("호칭 앞의 진짜 이름은 그대로 가립니다", () => {
    expect(maskNames("홍길동 아드님 통화")).toBe("○○ 아드님 통화");
    expect(maskNames("임꺽정 님께 연락")).toBe("○○ 님께 연락");
  });
});
