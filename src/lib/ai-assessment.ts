/**
 * AI 로 보내기 전에 개인을 알아볼 수 있는 글자를 가립니다.
 *
 * ⚠️ **완전하지 않습니다. 완전해질 수도 없습니다.** 한국어에서 "홍길녀가 전화 받으심"의
 *    홍길녀와 "김치가 상했다"의 김치를 정규식으로 가를 방법이 없습니다. 호칭도, 관계어도,
 *    사람에게만 붙는 조사도 없이 이름만 덩그러니 놓이면 못 잡습니다.
 *
 *    그래서 세 겹으로 둡니다 —
 *      ① 여기서 잡을 수 있는 것은 최대한 잡고(실측: 누출 사례 20건 중 19건 차단,
 *         남아야 할 표현 30건 중 손상 0건)
 *      ② 프롬프트에서 **"이름이 없다"고 거짓말하지 않고**, 모델에게 "혹시 보이더라도
 *         답에 옮겨 적지 말라"고 지시하고
 *      ③ 화면에서 **보낼 내용을 언제나 그대로 보여주고** 담당자가 보고 누르게 합니다.
 *
 *    ②가 특히 중요합니다. 예전에는 프롬프트 첫 줄이 "개인 식별 정보 없음"이라고 단언해
 *    두어서, 모델에게 "이름을 쓰지 말라"는 지시를 **아예 넣지 않았습니다.** 가리기가
 *    새는 순간 막을 것이 하나도 없었습니다.
 */
export function maskNames(text: string): string {
  return (
    text
      // ── 모양이 또렷한 것부터. 이름은 못 알아봐도 이쪽은 형태가 분명합니다 ──
      .replace(/\d{6}\s?-\s?[1-4]\d{6}/g, "(주민번호)")
      .replace(/[\w.+-]+@[\w-]+\.[\w.]+/g, "(이메일)")
      .replace(/\(0\d{1,2}\)\s?\d{3,4}[-.\s]?\d{4}/g, "(전화번호)")
      .replace(/0\d{1,2}[-.\s]?\d{3,4}[-.\s]?\d{4}/g, "(전화번호)")
      // 국제표기(+82 10 1234 5678)와 엔대시(010–1234–5678).
      .replace(/\+\d{1,3}[-–.\s]?\d{1,3}[-–.\s]?\d{3,4}[-–.\s]?\d{4}/g, "(전화번호)")
      .replace(/0\d{1,2}[-–.\s]\d{3,4}[-–.\s]\d{4}/g, "(전화번호)")
      // ★ 지역번호를 생략한 **시내 전화번호**(241-5600). 홀몸 어르신 댁 번호가
      //   기록에서 가장 흔히 이 꼴입니다. 앞뒤에 숫자가 붙으면 날짜·금액일 수
      //   있으니 경계를 둡니다.
      .replace(/(?<![\d-])\d{3}[-–]\d{4}(?![\d-])/g, "(전화번호)")
      .replace(/\b(19|20)\d{2}-\d{3,7}\b/g, "(회원번호)")
      // 생년월일은 앞에 말이 붙을 때만 가립니다. 그냥 날짜는 복귀 예정일일 수 있고,
      // 그건 판단에 꼭 필요한 정보입니다.
      .replace(
        /(생년월일|생일|출생)\s*:?\s*(19|20)?\d{2}[-./]\s?\d{1,2}[-./]\s?\d{1,2}/g,
        "$1 (날짜)",
      )
      // ── 주소 ──
      .replace(/[가-힣]{0,5}(아파트|빌라|연립|주공|맨션|타운)\s?\d*(동|단지|호)?/g, "(주소)")
      // 도로명("방송길 86"). 뒤에 한글·숫자가 이어지면 주소가 아닙니다("산책로 3바퀴").
      .replace(/[가-힣]{2,10}(로|길)\s?\d+(-\d+)?\s?(번지|번길|호)?(?![가-힣\d])/g, "(주소)")
      // 「동·읍·면·리 + 숫자」를 무조건 주소로 보면 "거동 1개월째"가 "(주소)개월째"가
      // 됩니다. 번지·호가 붙거나, 뒤에 단위가 안 붙을 때만 가립니다.
      .replace(/[가-힣]{1,5}(동|읍|면|리)\s?\d+(-\d+)?(번지|호)(?![가-힣])/g, "(주소)")
      .replace(/[가-힣]{2,5}(동|읍|면|리)\s?\d+(-\d+)?(?![가-힣\d])/g, "(주소)")
      // ── 이름 ① 뒤에 호칭이 붙는 꼴 ("홍길동 아드님", "임꺽정 님") ──
      //
      // ★ 예전에는 호칭 앞 두세 글자를 **무조건** 가렸습니다. 그래서 이런 일이 났습니다 —
      //     "요양원 알아보신다고 따님이 말씀"  →  "요양원 알아○○ 따님이 말씀"
      //     "무릎 아프다고 어르신 말씀"        →  "무릎 ○○ 어르신 말씀"
      //     "1948년생 어르신"                  →  "1948○○ 어르신"
      //
      //   첫 번째가 특히 위험합니다. 「알아보는 중」이 지워지면 AI 는 **위기** 대신
      //   **요양원입소**를 고르고, 아직 댁에 계신 어르신이 명단에서 영구히 빠집니다.
      //   이 파일 위쪽 주석과 회귀 테스트가 경고해 둔 바로 그 사고입니다.
      //
      //   그래서 이제 **이름처럼 생겼을 때만** 가립니다 — 첫 글자가 흔한 성이고,
      //   끝 글자가 동사 어미가 아닐 때. "아프다고"(아), "년생"(년)은 성이 아니라
      //   그대로 두고, "홍길동"·"임꺽정"는 그대로 가립니다.
      .replace(
        /([가-힣]{2,4})(?=\s*(?:님|씨|어르신|아드님|따님|할머니|할아버지|여사|선생님|사장님|원장님))/g,
        (m) =>
          NOT_A_NAME.has(m) || !SURNAME.includes(m[0]) || VERB_TAIL.includes(m[m.length - 1])
            ? m
            : "○○",
      )
      // ── 이름 ①-2 관계어가 이름 **뒤**에 오는 꼴 ("변사또 며느리", "홍길자 본인") ──
      //
      // ★ 현장 기록은 이 어순이 훨씬 흔한데 규칙에 없었습니다. 실측하면
      //   "변사또 며느리 통화함. 요양원 상담 중" 이 **통째로** 나갔습니다.
      //
      //   위 ① 의 호칭 목록에 그냥 더하면 안 됩니다. 「본인」·「가족」은 이름이 아닌
      //   말 뒤에도 붙기 때문입니다 — 실제로 "무릎 수술하셨다고 **본인이** 말씀하심"
      //   에서 「하셨다고」가 이름으로 잡혀 ○○ 로 지워졌습니다. 그래서 여기서는
      //   **이름처럼 생겼는지(looksLikeName)** 를 따로 확인합니다.
      .replace(
        /([가-힣]{3})(?=\s*(?:며느리|사위|자제분|손자|손녀|손주|조카|배우자|남편|부인|아내|보호자|본인|가족|유가족|상주))/g,
        (m) => (looksLikeName(m) ? "○○" : m),
      )
      // ── 이름 ② 앞에 관계어·「성함은」이 오는 꼴 ("딸 홍길순", "보호자 심학규") ──
      //
      // 이 자리가 예전에 가장 많이 샜습니다. 호칭이 안 붙으니 ①이 못 잡았습니다.
      //
      // ⚠️ 조사(이/가/은/는) 뒤에 **띄어쓰기를 반드시 요구**하는 이유:
      //
      //   예전에는 `(?:이|가|은|는)?` 였습니다. "딸 홍길순이 받으심" 에서 이 조사 자리가
      //   욕심을 내어 **이름 첫 글자 「이」를 먹어버리고**, 남은 「미숙이」를 이름 자리로
      //   넘겼습니다. 「미」는 흔한 성이 아니니 looksLikeName 이 false 를 냈고, 콜백이
      //   원문을 그대로 돌려주면서 **정규식은 이미 성공한 상태라 되돌아가지 않았습니다.**
      //   그래서 「홍길순」이 가려지지 않고 그대로 Anthropic 으로 갔습니다.
      //
      //   조사 뒤에 공백을 요구하면 "딸 홍길순이" 에서는 조사 자리가 비고 이름은
      //   「홍길순」으로 잡히며, "딸이 성춘향" 같은 원래 꼴도 그대로 잡힙니다.
      .replace(
        /(^|[^가-힣])(따님|아드님|자제분|자부|사위분|손주분|딸|아들|며느리|사위|손자|손녀|손주|조카|동생|형|누나|언니|오빠|남편|부인|아내|보호자|가족|자녀|이웃|담당자?|사회복지사|복지사|간호사|요양보호사|생활지도원|성함은?|이름은?|성명은?)\s*(?:(?:이|가|은|는)\s+)?([가-힣]{3})/g,
        (m, pre, rel, name) => (looksLikeName(name) ? `${pre}${rel} ○○` : m),
      )
      // ── 이름 ③ 사람에게만 붙는 조사 앞 ("심청이께", "홍길숙한테") ──
      .replace(/(?<![가-힣])([가-힣]{2,4})(?=(?:께서|께|에게|한테)(?![가-힣]))/g, (m) =>
        NOT_A_NAME.has(m) ? m : "○○",
      )
      // ── 이름 ③-2 **흔한 성 + 두 글자**가 사람처럼 쓰일 때 ──
      //
      // ★ 여기가 가장 크게 새던 자리입니다. 실측하면 아래가 전부 **그대로** 나갔습니다 —
      //
      //     "홍길자 본인 통화. 무릎 수술 후 거동 불편"
      //     "홍길남 사망하셨다고 주민센터에서 알려옴"
      //     "홍길녀가 전화 받으심"
      //
      //   ①은 이름 **뒤**에 호칭이 와야 하고, ③은 조사가 `께·에게·한테` 일 때만
      //   봅니다. 그런데 현장 기록에서 가장 흔한 것은 **이름이 문장 맨 앞에 오고**
      //   바로 조사(이/가/은/는/을/를)나 동작이 붙는 꼴입니다. 실명에 병명·사망까지
      //   붙어 그대로 Anthropic 으로 나갔습니다.
      //
      //   그물을 넓히되 **흔한 성으로 시작하는 세 글자**로 묶습니다. 성씨 제한이
      //   없으면 "요양원이"·"경로당은" 같은 말이 전부 걸립니다. 그래도 걸리는 말은
      //   NOT_A_NAME_3 가 빼 줍니다(전언·장례식·요양원 등 — 판단 근거가 지워지면
      //   AI 가 엉뚱한 갈래를 고릅니다).
      .replace(
        new RegExp(
          `(?<![가-힣])([${SURNAME}][가-힣]{2})` +
            `(?=(?:이|가|은|는|을|를|와|과|도|만|랑|의|한테|에게|께)?` +
            // ⚠️ 여기서 `\s` 를 쓰면 안 됩니다 — 템플릿 문자열이 역슬래시를 먹어
            //    정규식에 `s*` 가 들어갑니다(실제로 그렇게 새고 있었습니다).
            //    이 자리에 필요한 것은 공백뿐이므로 문자 그대로 적습니다.
            `(?:[ ]*(?:통화|연락|사망|돌아가|별세|임종|장례|입원|퇴원|수술|낙상|골절|치매|` +
            `[가-힣]{0,2}암|` +
            `뇌경색|뇌졸중|암|진단|판정|재활|전화|말씀|방문|확인|받으|하심|하셨|이심|씨|님)|` +
            `(?:이|가|은|는|을|를|와|과|도|만|랑)(?![가-힣])))`,
          "g",
        ),
        (m) => (NOT_A_NAME_3.has(m) || NOT_A_NAME.has(m) || VERB_TAIL.includes(m[2]) ? m : "○○○"),
      )
      // ── 이름 ④ 성만 쓰는 꼴 ("김씨", "박 여사") ──
      //
      // 예전 규칙은 `\b` 로 끝났는데, JS 의 \b 는 한글을 단어문자로 보지 않아 "씨" 뒤에서
      // **절대 성립하지 않습니다.** 규칙이 통째로 죽어 있었습니다. 호칭 뒤에는 조사가
      // 붙으므로("김씨**가** 그러는데") 조사도 허용합니다.
      .replace(
        /(?<![가-힣])([가-힣])(?=\s*(?:씨|할머니|할아버지|여사)(?:가|이|은|는|을|를|와|과|도|만|랑|의|에게|한테|께서|께)?(?![가-힣]))/g,
        (m) => (NOT_A_NAME.has(m) ? m : "○"),
      )
  );
}

export interface ClassifySuggestion {
  resultKind: string;
  resumeExpected: string | null;
  snoozeDays: number;
  /** 적으신 내용을 시간 순서로 꿴 두세 문장. */
  situation: string;
  /** 담당자가 다음에 실제로 할 일. "지켜보세요" 같은 말이 아니라 언제·무엇을·왜. */
  nextAction: string;
  /** 놓치기 쉬운 점(없으면 빈 문자열). */
  watchOut: string;
  /** 왜 그 갈래로 봤는지 한 문장. */
  reason: string;
  confidence: "high" | "low";
}

/**
 * 적으신 한 줄을 AI에 보내 분류를 제안받습니다.
 *
 * 실패하면 null 을 돌려줍니다 — 그러면 화면은 규칙이 낸 결과를 그대로 씁니다. AI가 안 되는
 * 날에도 기록은 남아야 합니다.
 */
export async function classifyWithAi(
  note: string,
  today: string,
): Promise<{ suggestion: ClassifySuggestion | null; error: string | null }> {
  const { data, error } = await supabase.functions.invoke("ai-assessment", {
    body: { mode: "classify", note: maskNames(note), today },
  });
  if (error) return { suggestion: null, error: error.message };
  if (data?.error) return { suggestion: null, error: String(data.error) };
  if (!data?.resultKind) return { suggestion: null, error: "AI 응답을 읽지 못했습니다" };
  return {
    suggestion: {
      resultKind: String(data.resultKind),
      resumeExpected: data.resumeExpected ?? null,
      snoozeDays: Number(data.snoozeDays ?? 0),
      situation: String(data.situation ?? ""),
      nextAction: String(data.nextAction ?? ""),
      watchOut: String(data.watchOut ?? ""),
      reason: String(data.reason ?? ""),
      confidence: data.confidence === "high" ? "high" : "low",
    },
    error: null,
  };
}
