// AI 판단 호출 — 위기 어르신에게 "왜 위험한지 한 문장"을 붙입니다.
//
// 실제 모델 호출은 Edge Function(supabase/functions/ai-assessment)에서 합니다. 이 파일은
// 화면 쪽에서 (1) 어르신 한 분의 **가린 요약**을 만들고 (2) 함수를 부르고 (3) 결과를
// 화면 상태에 반영하는 일만 합니다. API 키는 이 코드에 없습니다 — 서버에만 있습니다.
//
// 정확도 원칙: **1인 1호출**. 여러 명을 한 번에 보내지 않고, 한 분씩 순서대로 부릅니다.
// 개인정보: 실명을 보내지 않습니다. 아래 buildSummary 가 가린 이름·회원번호·숫자만 씁니다.
import { supabase } from "./supabase-client";
import {
  BASELINE_DAYS,
  describeAbsenceContext,
  describeVisitFrequency,
  describeDowPattern,
  getFollowupsForResident,
  RESULT_KIND_META,
  type WorklistEntry,
} from "./attendance-engine";

export interface AiRunResult {
  done: number;
  paused: boolean; // 비용 상한에 걸려 멈췄으면 true
  spent: number;
  cap: number;
  error?: string;
}

/**
 * 어르신 한 분을 AI에 보낼 "가린 요약"으로 만듭니다.
 *
 * 개인정보 최소화 원칙:
 *  · 실명·회원번호를 보내지 않습니다. 회원번호는 서버가 residentId로 따로 받아 저장에만
 *    쓰고, 이 프롬프트 본문에는 넣지 않습니다(회원번호로 재식별되는 것을 막습니다).
 *  · 담당자가 적은 확인 기록은 **maskNames 로 가려서** 보냅니다. 실명·전화번호·주소는
 *    가리고, "요양원 들어가셨다 함" 같은 내용은 그대로 둡니다 — 그게 판단의 핵심입니다.
 */
/** 지난 확인 기록을 몇 건까지 실어 보낼지. */
const FOLLOWUP_HISTORY_LIMIT = 5;
/** 한 건에서 잘라 보낼 글자 수. 현장 기록은 대개 두세 줄입니다. */
const FOLLOWUP_NOTE_LIMIT = 200;

/**
 * 지난 확인 기록을 AI 가 읽을 수 있게 정리합니다.
 *
 * ★ **적어 두신 내용을 가려서 함께 보냅니다.** 한동안 갈래와 날짜만 보냈는데, 그건
 *   과했습니다 — 막는 이유가 스스로 안 맞았습니다.
 *
 *   ① 같은 문장이 이미 나갑니다. 담당자가 확인 기록을 쓰고 AI 단추를 누르면
 *      classifyWithAi 가 `maskNames(note)` 로 **원문 전체**를 Anthropic 에 보냅니다.
 *      들어갈 때 이미 나간 문장을 나올 때만 막는 것은, 아무것도 지키지 못하면서
 *      설명만 나쁘게 만듭니다.
 *   ② 기관이 직접 적은 자기 기관 기록입니다. 7월에 "무릎 수술하셔서 한 달 못 나오심"
 *      이라고 적어 두고 8월에 같은 분을 다시 볼 때 그 문장을 못 읽는다면, 애초에
 *      적을 이유가 없는 기록입니다.
 *   ③ 갈래만으로는 판이 안 보입니다. 「일시적사정」 네 글자로는 "손주 보러 가심"과
 *      "허리를 다쳐 거동이 어려우심"이 구분되지 않습니다. 두 번째라면 담당자가 오늘
 *      해야 할 일이 완전히 다릅니다.
 *
 *   남는 위험은 maskNames 가 조사만 붙은 맨이름("홍길녀가 전화 받으심")을 못 잡는
 *   것입니다. 이건 분류 경로에서 이미 지고 있는 위험이라, 막을 자리는 여기가 아니라
 *   **가리기 자체를 고치는 쪽**입니다.
 */
function followupLines(e: WorklistEntry): string {
  const list = getFollowupsForResident(e.resident.id).slice(0, FOLLOWUP_HISTORY_LIMIT);
  if (list.length === 0) return "── 지난 확인 기록 ──\n- 아직 연락해 본 기록이 없습니다.";
  const rows = list.map((f) => {
    const kind = f.resultKind
      ? (RESULT_KIND_META[f.resultKind]?.label ?? f.resultKind)
      : f.outcome === "no_answer"
        ? "연락이 닿지 않음"
        : f.outcome === "needed"
          ? "도움이 더 필요했음"
          : "지금은 괜찮으심";
    const promise = f.resumeExpected ? ` · 그때 ${f.resumeExpected}쯤 나오신다고 하심` : "";
    const body = maskNames(f.note).replace(/\s+/g, " ").trim().slice(0, FOLLOWUP_NOTE_LIMIT);
    const quoted = body ? `\n  적어 둔 내용: "${body}"` : "";
    return `- (${f.checkedAt}) ${kind}${promise}${quoted}`;
  });
  return ["── 지난 확인 기록 (최신이 위. 실명·전화·주소는 가려서 보냅니다) ──", ...rows].join("\n");
}

/**
 * 이번이 재발이라는 사실을 **로직이 직접 말해 줍니다.**
 *
 * 위 목록만 줘도 AI 가 날짜를 보고 알아차릴 수는 있습니다. 그런데 알아차릴 때도 있고
 * 넘어갈 때도 있습니다 — 담당자가 가장 놓치면 안 되는 대목을 AI 기분에 맡길 수는
 * 없습니다. 그래서 숫자로 못 박아 보냅니다.
 */
function relapseLine(e: WorklistEntry): string {
  if (e.relapseCount <= 0) return "재발 여부: 지난 반년 안에는 이번이 처음 끊기신 것입니다.";
  return [
    `★ 재발 ${e.relapseCount + 1}회째입니다.`,
    `지난 반년 안에 연락이 닿아 다시 나오셨다가 또 끊긴 것이 ${e.relapseCount}번 있었습니다.`,
    "한 번 끊긴 것과 반복해서 끊기는 것은 다른 일입니다. 반드시 이 점을 짚어 주세요.",
  ].join(" ");
}

export function buildSummary(e: WorklistEntry): string {
  const r = e.resident;

  // 외부변수가 AI 문장으로 들어가는 자리입니다.
  //
  // 지금까지 날씨·행사는 계산만 하고 아무 데도 안 썼습니다. 판정(위기/주의)은 로직이
  // 이미 끝냈으니, AI가 할 일은 **왜 그런지 사람 말로 쓰는 것**입니다. 그때 "비도 안 왔고
  // 행사도 없던 평범한 날부터"라는 한마디가 붙느냐 마느냐가 담당자에게는 큰 차이입니다.
  //
  // 관리자 화면에서 날씨를 끄면 이 줄에서도 날씨가 빠집니다 — 스위치가 진짜로 결과를
  // 바꾸는 지점입니다.
  const ctx = describeAbsenceContext(r);

  return [
    // ⚠️ "개인 식별 정보 없음"이라고 **단언하면 안 됩니다.**
    //
    //   maskNames 는 완전하지 않습니다(조사만 붙은 맨이름은 못 잡습니다). 그런데 이
    //   첫 줄이 "없다"고 못 박아 두는 바람에, 서버 프롬프트에 **"이름을 답에 쓰지 말라"는
    //   지시를 아예 넣지 않았습니다.** 가리기가 새는 순간 막을 것이 하나도 없었고,
    //   모델이 옮겨 적은 실명은 residents.ai_summary 에 **저장되어 화면에 뜹니다.**
    //
    //   그래서 사실대로 적고, 지시는 서버 프롬프트에 둡니다.
    "대상: 어르신 한 분 (회원번호·전화·주소는 지웠고, 이름은 가렸습니다)",
    `이용 구분: ${r.mealTier}`,
    // 평소 빈도는 habitRate(마지막 방문일 기준)로 적습니다. baselineRate 로 적으면
    // 결석이 길수록 "원래 뜸하던 분"이 되어, AI 가 "평소 2주에 한 번 오시던 분"이라고
    // 써버립니다 — 주 3회 꼬박 오시던 분인데요.
    // "평소"가 어느 기간을 말하는지 AI 도 알아야 합니다.
    //
    // 담당자가 AI 문장을 읽고 "평소가 뭐 기준이냐"고 물을 수 있는데, 화면(판정 설명)은
    // 기간을 적고 AI 문장은 안 적으면 두 글이 다른 말을 하는 것처럼 보입니다. 숫자는
    // 상수에서 그대로 가져옵니다 — 글로 박아두면 상수를 바꿔도 따라오지 않습니다.
    // ⚠️ 라벨이 값과 같은 창을 말해야 합니다.
    //
    //   어제 "최근 운영일 60일 기준"이라고 붙였는데, 여기 값은 habitRate 이고 그 창은
    //   **마지막으로 오신 날까지**의 60 운영일입니다. 19일째 안 나오고 계신 분이라면
    //   19일 전에 끝난 창입니다 — "최근"이 아닙니다.
    //
    //   화면(상세)의 「평소 출석률 (최근 운영일 60일)」은 baselineRate(오늘 기준)를
    //   보여줍니다. 같은 라벨을 서로 다른 두 값에 붙여 놓으면, 맞추려던 불일치를 한 겹
    //   더 만드는 셈입니다. AI 가 이 말을 믿고 "최근 석 달 동안 주 4회 오시던 분"이라고
    //   쓰면 담당자가 달력에서 확인할 때 틀립니다.
    `평소 이용 빈도(마지막 방문일까지 운영일 ${BASELINE_DAYS}일 기준): ${describeVisitFrequency(e.habitRate)}`,
    `최근 30일 출석률: ${e.recentRate}%`,
    `현재 연속결석(운영일): ${e.consecutiveAbsence}일`,
    // 요일 리듬. 점수에는 이미 녹아 있는데 AI 는 그 사실을 모른 채 "19일 안 나오셨습니다"
    // 라고만 썼습니다. "금요일마다 오시던 분이 금요일을 세 번 건너뛰셨다"가 담당자에게는
    // 훨씬 구체적인 말입니다.
    e.dowPattern ? describeDowPattern(e.dowPattern) : "",
    // 「이분 리듬으로는 이례적이다」를 AI 도 알아야 합니다. 출석률만 주면
    // "주 3회 오시던 분이 8일 안 나오셨습니다" 라고만 쓰고, 그게 이분에게 네 배라는
    // 사실을 못 짚습니다 — 담당자가 전화를 걸지 말지 가르는 대목입니다.
    e.usualMaxGap > 0
      ? `평소 결석 최장 기간: ${e.usualMaxGap}일${e.rhythmBreak ? " ← 지금 이 선을 넘겼습니다(그래서 등급을 한 단계 올렸습니다)" : ""}`
      : "",
    // 확률(= e^{-절벽점수})은 **보내지 않습니다.**
    //
    // 사양 8-2 "숫자 점수·확률 언급 금지", 1장 "화면에 숫자 점수 표시" 금지. 입력에 넣으면
    // 모델이 "우연일 확률은 0.00%입니다" 라고 쓸 수 있고, 그 문장이 그대로 저장돼 화면에
    // 뜹니다 — 막아둔 숫자 노출이 AI 문장을 통해 우회로 일어납니다.
    // 대신 "평소와 얼마나 다른가"는 위의 빈도·출석률·연속결석으로 충분히 전해집니다.
    e.lastDate ? `마지막 방문: ${e.lastDate}` : "",
    "",
    "── 안 나오신 기간의 사정(외부변수) ──",
    ctx.line,
    "",
    `로직이 내린 판정: ${e.signal === "acute" ? "급성(갑자기 끊김)" : e.signal === "chronic" ? "만성(서서히 줄어듦)" : "관측 불가"}`,
    "",
    // 지난번에 연락해서 알아낸 것이 있으면 그것까지 보고 써야 합니다.
    //
    // "지난달에 통화했더니 추석이라 못 오신다고 하셨는데, 연휴가 끝나고도 3주째
    // 안 나오십니다" — 이런 문장은 확인 기록 없이는 쓸 수 없습니다. 같은 20일 결석이라도
    // 아무 연락도 없었던 20일과, 곧 나오신다 하고 지난 20일은 뜻이 다릅니다.
    //
    // 이름은 가리고 보냅니다(maskNames). 담당자가 쓴 글에는 가족 이름이 섞입니다.
    followupLines(e),
    "",
    relapseLine(e),
    `출결 키워드: ${e.keywords.join(", ") || "없음"}`,
  ]
    .filter(Boolean)
    .join("\n");
}

/**
 * 동시에 몇 분까지 함께 부를지.
 *
 * 왜 1이 아닌가 — 예전에는 `for … await` 로 **한 분 끝나야 다음 분**을 불렀습니다.
 * 한 호출에 드는 시간은 대부분 기다리는 시간입니다(Edge Function 깨우기 → 이번 달 누적
 * 비용 조회 → Anthropic 왕복 → 사용량·요약 저장). 실측하면 한 분에 4~6초쯤이라,
 * 12분이면 **1분 넘게** 화면이 멈춘 듯 서 있었습니다. 담당자는 그동안 아무것도 못 합니다.
 *
 * 왜 무제한이 아닌가 — 비용 상한 검사가 **서버에서 호출마다** 이뤄집니다. 동시에 N개가
 * 떠 있으면 마지막 한 건이 상한을 넘기는 순간에도 이미 출발한 N-1건은 끝까지 갑니다.
 * 즉 최대 N-1건만큼 상한을 넘길 수 있습니다. 한 건이 1.6원쯤이니 4면 최대 5원 — 월
 * 상한 1만 원 대비 무시할 수 있는 초과입니다. 여기를 키우면 그 초과도 같이 커집니다.
 */
const AI_CONCURRENCY = 4;

/**
 * 대상 목록을 AI로 분석합니다(1인 1호출, 동시 {@link AI_CONCURRENCY}건).
 *
 * 매 호출마다 서버가 이번 달 누적 비용을 확인해, 상한(₩10,000≈$7)을 넘으면 paused=true 로
 * 돌려줍니다. 그러면 **새로 출발시키지 않습니다** — 이미 떠 있는 건은 끝까지 갑니다.
 *
 * onProgress 로 한 건 끝날 때마다 진행 상황을 알려, 화면이 하나씩 갱신되게 합니다.
 * 순서는 보장하지 않습니다 — 먼저 끝난 분부터 화면에 올라옵니다.
 */
export async function runAiAssessments(
  entries: WorklistEntry[],
  onProgress?: (residentId: string, summary: string, spent: number, cap: number) => void,
  model = "claude-haiku-4-5-20251001", // 가장 저렴한 모델(입력 $1 / 출력 $5 per 1M). 월 상한 $7과 함께 씀
): Promise<AiRunResult> {
  let done = 0;
  let spent = 0;
  let cap = 7;
  let paused = false;
  let failure: string | null = null;
  let next = 0;

  // 한 명을 처리합니다. 돌아오는 값이 아니라 위쪽 변수를 고쳐 나갑니다 —
  // 여러 갈래가 동시에 끝나므로, 마지막으로 돌아온 값이 최신 누적액입니다.
  const one = async (e: WorklistEntry): Promise<void> => {
    const { data, error } = await supabase.functions.invoke("ai-assessment", {
      body: { residentId: e.resident.id, summary: buildSummary(e), model },
    });

    if (error) {
      failure ??= error.message; // 처음 난 오류만 남깁니다. 넷이 같이 실패해도 메시지는 하나.
      return;
    }
    if (data?.paused) {
      // 상한 도달 — 이분은 분석 안 됐습니다. 새로 출발시키지 않습니다.
      paused = true;
      spent = Number(data.spent ?? spent);
      cap = Number(data.cap ?? cap);
      return;
    }
    if (data?.error) {
      failure ??= data.error;
      return;
    }

    done++;
    spent = Number(data.spent ?? spent);
    cap = Number(data.cap ?? cap);
    onProgress?.(e.resident.id, String(data.summary ?? ""), spent, cap);

    // 이번 호출로 상한을 넘겼으면 더 출발시키지 않습니다.
    if (data.reachedCap) paused = true;
  };

  // 일꾼 몇을 세워 두고 목록에서 하나씩 집어 가게 합니다. 한 명이 오래 걸려도
  // 나머지 일꾼은 계속 다음 분을 집으므로, 느린 한 건이 전체를 붙잡지 않습니다.
  const worker = async (): Promise<void> => {
    for (;;) {
      if (paused || failure) return;
      const i = next++;
      if (i >= entries.length) return;
      await one(entries[i]);
    }
  };

  await Promise.all(
    Array.from({ length: Math.min(AI_CONCURRENCY, entries.length) }, () => worker()),
  );

  // ⚠️ 상한 도달을 오류로 덮지 않습니다.
  //
  // 동시 4건이라 「상한 도달」과 「다른 오류」가 같은 순간에 돌아오는 것이 구조적으로
  // 가능합니다. 예전에는 failure 가 있으면 paused 를 무조건 false 로 덮었고, 화면은
  // error 를 먼저 보므로 「월 비용 상한에 도달해 멈췄습니다」가 뜨지 않았습니다.
  // 담당자는 일시적 오류로 읽고 단추를 다시 누릅니다 — 그래서 상한을 더 넘깁니다.
  if (failure) return { done, paused, spent, cap, error: failure };
  return { done, paused, spent, cap };
}

/** 이번 달 누적 AI 비용(USD)과 상한을 읽어옵니다. 화면 표시용. */
export async function fetchAiSpend(): Promise<{ spent: number; cap: number }> {
  const [{ data: spend }, { data: capRow }] = await Promise.all([
    supabase.rpc("ai_month_spend"),
    supabase.from("app_settings").select("value").eq("key", "ai_monthly_cap_usd").maybeSingle(),
  ]);
  const cap = Number((capRow?.value as { cap?: number } | null)?.cap ?? 7);
  return { spent: Number(spend ?? 0), cap };
}

