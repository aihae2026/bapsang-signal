import { describe, expect, it } from "bun:test";
import { classifyFollowupNote } from "./followup-classify";
import type { ResultKind } from "./attendance-engine";

const TODAY = "2026-09-15";
const kindOf = (memo: string) => classifyFollowupNote(memo, TODAY).resultKind;

