describe("단어 일부가 우연히 겹쳐도 오분류하지 않는다", () => {
  it('"입소문"은 "입소"가 아니다', () => {
    expect(kindOf("입소문 듣고 오시던 분인데 요즘 안 나오심")).not.toBe("요양원입소");
  });
  it('"특이사항 없음"이 이사전출로 분류되면 안 된다', () => {
    // 특「이사」항 — 가장 흔한 메모가 영구 종료로 분류되던 실제 사고
    expect(kindOf("특이사항 없음")).not.toBe("이사전출");
    expect(kindOf("특이사항 없이 잘 지내심")).not.toBe("이사전출");
  });
  it("한시적 표현이 있으면 종료 계열보다 앞선다", () => {
    // "아들 집"이 이사전출로 읽혀 영구 종료되던 사례
    expect(kindOf("아들 집에 잠시 가 계셔서 당분간 못 나오심")).toBe("일시적사정");
  });
});

describe("직접 확인한 내용은 제대로 분류한다", () => {
  const cases: [ResultKind, string][] = [
    ["요양원입소", "요양원 입소하셨습니다. 가족 확인함"],
    ["사망", "지난주 돌아가셨습니다"],
    ["위기", "통화됨. 무릎 수술로 2주 입원 예정이라 하심"],
    ["이용감소", "통화됨. 기력이 없어 예전만큼 자주 못 나오신다고 하심"],
    ["일시적사정", "너무 더워서 안 나오고 있음. 추석 이후 나올 예정"],
    ["일자리프로그램참여", "노인일자리 참여중이심"],
    ["타기관이용", "가까운 경로당 다니심"],
  ];
  for (const [want, memo] of cases) {
    it(`"${memo.slice(0, 24)}…" → ${want}`, () => {
      expect(kindOf(memo)).toBe(want);
    });
  }
});

describe("복귀 예정일 추정", () => {
  it("명절은 규칙이 짐작하지 않는다 — 공휴일 표가 채웁니다", () => {
    // 예전에는 plus(21) 로 짐작해 2026 추석에 10/07 을 냈습니다. 정답은 9/28(연휴 뒤 첫
    // 평일)이고 getNoteContext 가 공휴일 표에서 정확히 계산합니다. 두 곳이 다른 값을 내면
    // 화면은 규칙 값을 먼저 쓰므로, AI 가 꺼져 있을 때 9일 늦게 발견하게 됩니다.
    const r = classifyFollowupNote("더워서 못 나오심. 추석 이후 나올 예정", TODAY);
    expect(r.resumeExpected).toBeNull();
  });
  it("명시한 날짜를 그대로 읽는다", () => {
    const r = classifyFollowupNote("당분간 쉬시고 10월 5일부터 나오신다고 함", TODAY);
    expect(r.resumeExpected).toBe("2026-10-05");
  });
});

describe("애매하면 가장 보수적인 값", () => {
  it("빈 메모", () => {
    expect(kindOf("")).toBe("확인불가");
  });
  it("아무 규칙에도 안 걸리는 문장", () => {
    const r = classifyFollowupNote("특이사항 없음", TODAY);
    expect(r.resultKind).toBe("확인불가");
    expect(r.confidence).toBe("low");
  });
});

