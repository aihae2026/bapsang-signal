describe("직접 확인한 것은 전언으로 오해하지 않는다", () => {
  // 위 규칙을 넓히면서 정상 문장까지 확인불가로 밀어내면, 담당자가 통화해서 알아낸 것이
  // 없었던 일이 됩니다. 반대 방향도 함께 묶어 둡니다.
  it("직접 통화해 입원을 확인하면 위기", () => {
    expect(kindOf("직접 통화함. 낙상으로 입원하셨다고 본인이 말씀하심")).toBe("위기");
  });
  it("본인과 통화해 들은 일시적 사정은 일시적사정", () => {
    expect(kindOf("본인 통화. 손주 보러 서울 가셨고 추석 지나 오신다 하심")).toBe("일시적사정");
  });
  it("연락이 안 되면 어미와 무관하게 확인불가", () => {
    expect(kindOf("전화 안 받으심. 요양원 가셨다더라")).toBe("확인불가");
  });
});

// ── 사망 표현 ────────────────────────────────────────────────────
//
// 현장에서 「지난달 돌아가심」이라고 적었는데 「확인불가」가 됐습니다. 옛 규칙이
// `돌아가(셨|시)` 라서 **「돌아가심」·「돌아가신」을 못 잡았기** 때문입니다. 돌아가신
// 분이 계속 전화 목록에 떠서, 담당자에게도 유가족에게도 할 짓이 아니었습니다.
describe("사망 — 직접 적은 표현은 잡고, 전해 들은 말은 막는다", () => {
  const 직접 = [
    "사망",
    "돌아가심",
    "죽으심",
    "죽음",
    "사망하심",
    "절명하심",
    "지난달 돌아가심",
    "별세하심",
    "작고하심",
    "임종하심",
    "운명하셨습니다",
    "타계하심",
    "고인이 되셨습니다",
    "영면하심",
    "부고 받음",
    "8월 15일 사망하심. 유가족 확인",
    // '들음'이 들어 있지만 '직접'이 앞에 붙으면 전언이 아닙니다.
    "따님께 직접 들음 — 돌아가심",
  ];
  for (const memo of 직접) {
    it(`"${memo}" — 사망으로 읽는다`, () => {
      expect(kindOf(memo)).toBe("사망");
    });
  }

  // 「상(喪)을 당하다」는 어르신 본인이 아니라 가족이 돌아가셨다는 뜻으로 더 많이 씁니다.
  // 사망으로 읽으면 살아 계신 분이 명단에서 사라집니다.
  it('"상 당하셨다고 함" — 사망으로 읽지 않는다', () => {
    expect(kindOf("상 당하셨다고 함")).not.toBe("사망");
  });
});

describe("어르신 번호는 안 되지만 다른 분과는 통화가 된 경우", () => {
  // 실제로 담당자가 이렇게 적었는데 「확인불가」가 나왔습니다. 「없는 번호」가 맨 앞
  // 규칙에 걸려, 뒤에 적힌 「배우자와 통화함 · 사망하심」을 읽지도 않았습니다.
  it("결번이어도 배우자와 통화해 들었으면 사망으로 읽습니다", () => {
    const note = [
      "없는 번호로 확인되어 비상 연락처 확인하여 배우자와 통화함.",
      "8월에 사망하심.",
    ].join(String.fromCharCode(10));
    expect(kindOf(note)).toBe("사망");
  });

  it("보호자와 통화해 확인했으면 이사전출로 읽습니다", () => {
    expect(kindOf("없는 번호. 보호자와 통화하여 확인함 — 이사 가셨음")).toBe("이사전출");
  });

  // ↓ 여기가 풀리면 안 됩니다. 아무에게도 닿지 못한 것은 여전히 확인불가입니다.
  it("다른 데도 못 물어봤으면 그대로 확인불가", () => {
    expect(kindOf("전화 안 받으심. 배우자 연락처도 없음")).toBe("확인불가");
    expect(kindOf("입원하셨다는데 전화는 안 받으심")).toBe("확인불가");
    expect(kindOf("몇 차례 방문했으나 부재로 못 뵈었음")).toBe("확인불가");
  });

  // 전언 차단은 그대로 살아 있어야 합니다 — 97세 독거 어르신 사고 그 자리입니다.
  it("연락이 안 된 채 전해 들은 말로는 여전히 명단에서 빼지 않습니다", () => {
    expect(kindOf("전화 안 받으심 + 요양원 가셨다는 말도 있어")).toBe("확인불가");
  });
});

