/** "추석 이후", "다음 주", "10월부터" 같은 복귀 언급에서 날짜를 추정합니다. */
function guessResumeDate(memo: string, todayStr: string): string | null {
  const [ty, tm, td] = todayStr.split("-").map(Number);
  const today = new Date(ty, tm - 1, td);
  const fmt = (d: Date) =>
    `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
  const plus = (n: number) => {
    const d = new Date(today);
    d.setDate(d.getDate() + n);
    return fmt(d);
  };

  // ── 복귀 예정일 읽기 ─────────────────────────────────────────
  //
  // 이 함수가 내놓는 날짜는 **어르신을 그날까지 위기 목록에서 빼둡니다.** 그래서 틀리면
  // 그만큼 늦게 발견합니다. 실제로 두 번 사고가 났습니다.
  //
  //   "8월부터 장기 요양으로 병원에 가 계시며…"  → 2027-08-01  (1년)
  //   "7월 20일부터 손주 봐주느라 못 나오심"      → 2027-07-20  (10개월)
  //
  // 둘 다 **지나간 일의 시작점**인데 미래 복귀일로 읽었습니다. 앞의 것만 고치고 뒤의 것을
  // 놓쳤던 이유는 방어를 "○월"에만 붙이고 "○월 ○일"에는 안 붙였기 때문입니다. 이제
  // 세 겹으로 막습니다.
  //
  //   ① 모른다고 하셨으면 아예 추정하지 않습니다
  //   ② 과거를 가리키는 말이 붙어 있으면 읽지 않습니다 ("부터", "계심", "가 계시")
  //   ③ 마지막 그물 — 오늘부터 6개월을 넘는 날짜는 자동으로 채우지 않습니다
  //
  // ③이 핵심입니다. 앞의 둘을 빠져나가는 표현이 또 나와도, 어르신이 반년 넘게 사라지는
  // 일만은 막습니다. 담당자가 정말 먼 날짜를 알고 있다면 직접 고르면 됩니다.
  const UNKNOWN_RETURN = /모른다|모름|모르겠|알 수 없|미정|기약/;
  const PAST_START = /부터[^.]{0,30}(계시|계심|하고 있|하는 중|중이|못 나오|안 나오|안 오)/;
  const RETURN_VERB = /나오|오신|오실|복귀|참석|퇴원|오기로|온다고/;

  /** 오늘부터 6개월 넘게 뒤면 버립니다. 그만큼 목록에서 사라지는 일은 없어야 합니다. */
  const withinHalfYear = (dateStr: string): string | null => {
    const limit = new Date(today);
    limit.setMonth(limit.getMonth() + 6);
    return dateStr <= fmt(limit) ? dateStr : null;
  };

  if (UNKNOWN_RETURN.test(memo)) return null;

  // 연·월·일이 다 적힌 경우는 담당자가 또렷이 적은 것이라 그대로 씁니다.
  const iso = memo.match(/(20\d{2})[-./](\d{1,2})[-./](\d{1,2})/);
  if (iso) return withinHalfYear(`${iso[1]}-${iso[2].padStart(2, "0")}-${iso[3].padStart(2, "0")}`);

  // "○월 ○일" — 복귀를 뜻할 때만. 과거 시작점이면 읽지 않습니다.
  const md = memo.match(/(\d{1,2})\s*월\s*(\d{1,2})\s*일/);
  if (md && !PAST_START.test(memo) && RETURN_VERB.test(memo)) {
    const m = Number(md[1]);
    const d = Number(md[2]);
    // 같은 달인데 날짜가 지났으면 내년이 아니라 다음 달로 봅니다. "9월 5일"을 2027년으로
    // 미는 것보다, 가까운 미래로 두고 담당자가 고치게 하는 편이 안전합니다.
    let y = today.getFullYear();
    const asThisYear = `${y}-${String(m).padStart(2, "0")}-${String(d).padStart(2, "0")}`;
    if (asThisYear < todayStr) y += 1;
    return withinHalfYear(`${y}-${String(m).padStart(2, "0")}-${String(d).padStart(2, "0")}`);
  }

  // "○월" 만 적힌 경우 — 역시 복귀를 뜻할 때만.
  const monthOnly = PAST_START.test(memo)
    ? null
    : memo.match(
        /(\d{1,2})\s*월\s*(?:에|쯤|경|중순|초|말)?\s*(?:부터\s*)?(?:다시\s*)?(?:나오|오신|오실|복귀|참석)/,
      );
  if (monthOnly) {
    const m = Number(monthOnly[1]);
    const y = today.getFullYear() + (m < tm ? 1 : 0);
    return withinHalfYear(`${y}-${String(m).padStart(2, "0")}-01`);
  }

  // 명절은 여기서 짐작하지 않습니다.
  //
  // getNoteContext 가 공휴일 표에서 정확한 날짜를 계산합니다(2026 추석 → 9/28). 여기서
  // plus(21) 로 짐작하면 10/07 이 나와 9일이 어긋나고, 화면은 규칙 값을 먼저 쓰기 때문에
  // **AI 가 꺼져 있으면 9일 늦게 발견**하게 됩니다. 짐작이 필요 없는 것을 짐작하지 않습니다.
  if (/다음\s*주|담주/.test(memo)) return plus(7);
  if (/다음\s*달|담달/.test(memo)) return plus(30);
  if (/내일/.test(memo)) return plus(1);
  if (/이번\s*주/.test(memo)) return plus(3);
  return null;
}

/**
 * 메모를 분류합니다. 애매하면 confidence를 low로 두고 **가장 보수적인 값**을 고릅니다 —
 * 잘못 분류해서 목록에서 빠지는 것보다, 남아 있어서 한 번 더 확인하는 편이 낫습니다.
 */
/**
 * 복귀 예정일의 마지막 그물 — 오늘부터 반년 넘는 날짜는 쓰지 않습니다.
 *
 * 이 날짜는 **그날까지 어르신을 목록에서 빼둡니다.** 그래서 틀리면 그만큼 늦게 찾아뵙게
 * 됩니다. 규칙 쪽에는 이미 이 그물이 있는데 AI 쪽에는 없었습니다 — "몸이 안 좋아 당분간
 * 못 나오심" 한 줄에 AI 가 2027-06-01 을 내면 **아홉 달간 모든 목록에서 사라집니다.**
 * 규칙만 돌았으면 걸렸을 값입니다. AI 를 켜야만 뚫리는 구멍이라 밖으로 냅니다.
 */
export function withinHalfYear(dateStr: string | null, todayStr: string): string | null {
  if (!dateStr || !/^\d{4}-\d{2}-\d{2}$/.test(dateStr)) return null;
  const [y, m, d] = todayStr.split("-").map(Number);
  const limit = new Date(y, m - 1 + 6, d);
  const limitStr = `${limit.getFullYear()}-${String(limit.getMonth() + 1).padStart(2, "0")}-${String(limit.getDate()).padStart(2, "0")}`;
  if (dateStr < todayStr) return null; // 지나간 날짜는 복귀일이 아닙니다
  return dateStr <= limitStr ? dateStr : null;
}

export function classifyFollowupNote(memo: string, todayStr: string): StructuredResult {
  const text = memo.trim();
  if (!text) {
    return {
      resultKind: "확인불가",
      resumeExpected: null,
      confidence: "low",
      reason: "내용이 비어 있어 분류할 수 없습니다",
    };
  }

  // ★ 1순위 — 연락이 닿지 않았다면 그것으로 끝입니다.
  //   "입원하셨다는데 전화는 안 받으심"이면 위기가 아니라 확인불가입니다. 전해 들은
  //   이야기로 감시를 풀면 안 됩니다. 연락이 안 되는 것 자체가 신호입니다.
  //   다만 **다른 분과는 통화가 된** 경우는 예외입니다(REACHED_VIA).
  //   어르신 번호가 결번이어도 배우자에게 들어 알아냈으면, 확인하지 못한 것이 아닙니다.
  const reachedSomeone = REACHED_VIA.some((re) => re.test(text));
  if (UNREACHABLE.some((re) => re.test(text)) && !reachedSomeone) {
    return {
      resultKind: "확인불가",
      resumeExpected: null,
      confidence: "high",
      reason:
        "연락이 닿지 않았다는 내용입니다. 연락 불가는 해제 사유가 아니라 그 자체로 신호라, 목록에 그대로 둡니다",
    };
  }

  // ★ 전언인지는 **어미가 아니라 누구에게 들었나**로도 가릅니다.
  //
  //   HEARSAY 는 「…더라」·「들음」·「말도 있어」 같은 **말끝**만 봤습니다. 그래서
  //   어미를 안 쓰고 단정해 적으면 그대로 뚫렸습니다 —
  //
  //     "이웃 확인 결과 요양원 입소하심"   → 요양원입소 · 확신 높음 → 영구 제외
  //     "동네 분 말씀으로 이사 가심"       → 이사전출 · 확신 높음 → 영구 제외
  //     "경로당에서 확인하니 이사 가셨음"  → 이사전출 · 확신 높음 → 영구 제외
  //
  //   셋 다 담당자가 어르신도 가족도 만나지 못한 건입니다. 「확인」이라는 낱말이
  //   붙었다고 확인이 되는 것이 아닙니다 — **누가 말했는가**가 기준입니다.
  //   97세 독거 어르신 사고가 정확히 이 모양이었고, 막았다고 적어 둔 방어가
  //   말끝 하나 바꾸면 비껴갔습니다.
  const fromOutsider = OUTSIDER.some((re) => re.test(text));
  // 가족이 「직접 들었다」고 못박아도, 그 가족이 **이웃 말을 옮긴 것**이면 전언입니다.
  //   "따님이 이웃에게 전해 들었다고 함 — 요양원 입소하심"
  const hearsay =
    fromOutsider || (HEARSAY.some((re) => re.test(text)) && !DIRECT.some((re) => re.test(text)));

  for (const rule of RULES) {
    if (!rule.re.test(text)) continue;

    // ★ 2순위 — 전해 들은 이야기로는 **종료(앞으로 확인 대상에서 제외)로 보내지 않습니다.**
    //   "요양원 가셨다는 말도 있어"는 확인해야 할 단서이지 확인된 사실이 아닙니다.
    // ★ 사망도 전언이면 막습니다. 한때 예외로 뺐다가 되돌렸습니다.
    //
    //   「돌아가셨대」는 누군가 그렇게 말했다는 뜻이지 확인된 사실이 아닙니다. 사망으로
    //   찍으면 그분은 모든 화면에서 영구히 사라지고, 살아 계셨다면 **아무도 다시 보지
    //   않습니다.** 잘못 찍었을 때 치르는 값이 97세 독거 어르신 사고와 같습니다.
    //
    //   대신 아래 reason 에 「'사망'으로 볼 만한 내용이 있다」고 분명히 적어 담당자가
    //   한 번에 고를 수 있게 합니다. 직접 들으셨으면 그 자리에서 고르시면 됩니다.
    if (hearsay && TERMINAL.includes(rule.kind)) {
      return {
        resultKind: "확인불가",
        resumeExpected: null,
        confidence: "low",
        reason: `'${rule.kind}'로 볼 만한 내용이 있지만 **전해 들은 이야기**로 읽힙니다. 직접 확인하기 전까지는 목록에 둡니다 — 맞다면 아래에서 직접 골라주세요`,
      };
    }

    return {
      resultKind: rule.kind,
      resumeExpected:
        rule.kind === "일시적사정" || rule.kind === "일자리프로그램참여"
          ? guessResumeDate(text, todayStr)
          : null,
      // 전언이 섞여 있으면 확신을 낮춰 "확인해주세요"를 띄웁니다.
      confidence: rule.confident && !hearsay ? "high" : "low",
      reason: hearsay
        ? "전해 들은 내용이 섞여 있어 확신을 낮췄습니다. 맞는지 봐주세요"
        : "적어주신 내용에서 이렇게 읽었습니다",
    };
  }

  return {
    resultKind: "확인불가",
    resumeExpected: guessResumeDate(text, todayStr),
    confidence: "low",
    reason: "어디에도 딱 들어맞지 않아 가장 보수적인 값으로 두었습니다. 직접 골라주세요",
  };
}
