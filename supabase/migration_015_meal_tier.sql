-- 어르신별 식사 이용 구분(일반 3,500원 / 감면 1,800원 / 무료급식).
--
-- 왜 넣는가: 무료·감면은 수급·저소득에 해당하는 분들입니다. 같은 정도로 발길이 끊겼을 때
-- 누구를 먼저 찾아뵐지 정하는 근거가 됩니다. 실제 자료로 보면 3,736분 중 일반 2,919명,
-- 무료급식 484명, 감면 333명입니다.
--
-- 값은 앤컴 결제 기록에서 나옵니다(가장 많이 이용한 구분). 금액 자체는 저장하지 않습니다 —
-- 판단에 필요한 것은 "어느 구분에 해당하는가"이지 얼마를 냈는지가 아니고, 금액까지 두면
-- 그만큼 더 민감한 자료를 들고 있게 됩니다.
--
-- ⚠️ 경제적 형편에 관한 정보입니다. 화면에서는 위험도 판단의 근거로만 쓰고, 목록에 크게
--    붙여 어르신을 구분 짓는 표시로 쓰지 않습니다.

alter table residents
  add column if not exists meal_tier text not null default '일반'
  check (meal_tier in ('일반', '감면', '무료급식'));

-- 확인
select meal_tier, count(*) from residents group by 1 order by 2 desc;
