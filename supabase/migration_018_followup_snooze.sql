-- 확인 기록 "며칠간 안심"(스누즈) 지원
--
-- 담당자가 위기 어르신에게 연락해 사유(가족 방문·입원·여행 등)를 확인하고 "며칠간은
-- 개입 불필요"로 판단했을 때, 그 기간 동안 위기 목록에서 빼기 위한 기한을 저장합니다.
-- 이 날짜가 지나면 앱이 자동으로 다시 위기 목록에 올립니다(사유가 끝났는데도 계속
-- 안 나오시면 다시 봐야 하니까요).
--
-- 이 컬럼이 없어도 기존 "개입 필요/불필요" 기록은 그대로 동작합니다(앱이 값이 있을 때만
-- 이 컬럼에 씁니다). 안심 기능을 쓰려면 이 마이그레이션을 한 번 실행하세요.
--
-- 실행: Supabase 대시보드 → SQL Editor 에 붙여넣고 Run.

alter table followups
  add column if not exists snooze_until date;

comment on column followups.snooze_until is
  '개입 불필요 + 사유 확인 시, 이 날짜까지 위기 목록에서 제외(지나면 자동 복귀). null이면 상시 표시.';
