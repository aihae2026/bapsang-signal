-- migration_028 — 「기한 없이 멈춤 · 다시 나오시면 새로 시작」 갈래를 더합니다
-- ════════════════════════════════════════════════════════════════════
--
-- 왜 필요한가:
--
--   확인 기록 창의 「기한 없음」 단추가 지금은 **아무 일도 안 하는 단추**였습니다.
--   기한을 안 걸면 그 어르신은 목록에서 빠지지도, 다시 오지도 않은 채 그냥 남았습니다.
--
--   그런데 현장에서 이 단추가 필요한 상황은 따로 있습니다 —
--
--     "요양원 가신 건 아니고, 당분간은 안 나오실 것 같은데 언제일지는 모르겠다"
--     "타 기관 다니시는 중. 다시 오실 수도 있고 아닐 수도 있고"
--
--   이런 분께 1개월·3개월 같은 기한을 억지로 붙이면, 그 날짜에 아무 근거 없이 다시
--   위기로 떠서 담당자가 또 전화를 겁니다. 반대로 종결해 버리면 **다시 나오셔도
--   영영 안 보입니다**(종결은 출석을 아예 보지 않습니다).
--
--   필요한 것은 그 사이입니다 — **지금은 멈추되, 다시 나오시는 날 자동으로 깨어나는 것.**
--
-- 어떻게 도는가:
--
--   status 가 '보류' 이므로 getMemberState 의 보류 경로를 그대로 탑니다 —
--     · 판정을 멈춥니다(목록·위기·주의 어디에도 안 뜹니다)
--     · **기록일 이후 출석이 한 번이라도 잡히면 자동 해제**
--     · 해제 뒤 30 운영일은 판정을 쉽니다(그동안 새 출석 패턴이 쌓입니다)
--     · 그 뒤부터는 **새로 쌓인 리듬으로** 다시 판정합니다
--
--   60일 넘게 안 나오신 분이 다시 오시면 자료가 새로 쌓이는 것과 같은 방식입니다.
--   담당자가 손으로 되돌릴 필요가 없습니다.
--
-- 실행: Supabase 대시보드 → SQL Editor → 붙여넣고 Run
-- 여러 번 실행해도 안전합니다.

alter table followups drop constraint if exists followups_result_kind_check;
alter table followups
  add constraint followups_result_kind_check
  check (result_kind is null or result_kind in (
    '위기', '사망', '요양원입소', '이사전출', '급식자격상실',
    '타기관이용', '일자리프로그램참여', '일시적사정', '이용감소', '확인불가',
    '판정중단'
  ));
